import 'device.dart';

/// A device as described inside an introduction. Unlike [TrustedDevice] it
/// carries where the device can be reached, because the two devices being
/// introduced to each other have no record of one another yet.
class IntroPeer {
  const IntroPeer({
    required this.deviceId,
    required this.name,
    required this.platform,
    required this.model,
    required this.host,
    required this.port,
    required this.fingerprint,
  });

  final String deviceId;
  final String name;
  final DevicePlatform platform;
  final String model;
  final String host;
  final int port;
  final String fingerprint;

  IntroPeer copyWith({String? host}) => IntroPeer(
        deviceId: deviceId,
        name: name,
        platform: platform,
        model: model,
        host: host ?? this.host,
        port: port,
        fingerprint: fingerprint,
      );

  Map<String, dynamic> toJson() => <String, dynamic>{
        'deviceId': deviceId,
        'name': name,
        'platform': platform.name,
        'model': model,
        'host': host,
        'port': port,
        'fingerprint': fingerprint,
      };

  factory IntroPeer.fromJson(Map<String, dynamic> json) => IntroPeer(
        deviceId: json['deviceId'] as String? ?? '',
        name: json['name'] as String? ?? 'A device',
        platform: platformFromString(json['platform'] as String?),
        model: json['model'] as String? ?? '',
        host: json['host'] as String? ?? '',
        port: (json['port'] as num?)?.toInt() ?? 0,
        fingerprint: json['fingerprint'] as String? ?? '',
      );
}

/// "I trust you both — would you like to connect to each other?"
///
/// [secret] is generated by the introducer and handed to both sides. Neither
/// device can complete the pairing without it, and it is only registered once
/// that side has consented, so the pairing cannot happen unless both agree.
class IntroOffer {
  const IntroOffer({
    required this.introId,
    required this.secret,
    required this.introducer,
    required this.counterpart,
  });

  final String introId;
  final String secret;
  final IntroPeer introducer;
  final IntroPeer counterpart;

  Map<String, dynamic> toJson() => <String, dynamic>{
        'introId': introId,
        'secret': secret,
        'introducer': introducer.toJson(),
        'counterpart': counterpart.toJson(),
      };

  factory IntroOffer.fromJson(Map<String, dynamic> json) => IntroOffer(
        introId: json['introId'] as String? ?? '',
        secret: json['secret'] as String? ?? '',
        introducer: IntroPeer.fromJson(
          (json['introducer'] as Map?)?.cast<String, dynamic>() ??
              <String, dynamic>{},
        ),
        counterpart: IntroPeer.fromJson(
          (json['counterpart'] as Map?)?.cast<String, dynamic>() ??
              <String, dynamic>{},
        ),
      );
}

/// The state of one introduction on this device.
///
/// The pairing only proceeds when [accepted] and [counterpartAccepted] are both
/// true — that is what makes a denial on either side cancel it for both.
class IntroSession {
  IntroSession(this.offer);

  final IntroOffer offer;

  /// This device has said yes.
  bool accepted = false;

  /// The other device has said yes.
  bool counterpartAccepted = false;

  /// Either side said no.
  bool declined = false;

  /// The pairing call has already been made.
  bool completed = false;

  /// Waiting on this device to choose.
  bool get awaitingUs => !accepted && !declined && !completed;

  /// Both sides agree, so the pairing may go ahead.
  bool get readyToPair =>
      accepted && counterpartAccepted && !declined && !completed;
}
